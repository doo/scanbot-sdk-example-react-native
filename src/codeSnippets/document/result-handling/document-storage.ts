import ScanbotSDK, {ScanbotDocument} from 'react-native-scanbot-sdk';

async function createDocument() {
  /** Create a document with a UUID */
  const document = await ScanbotDocument.createDocumentFromImages({});
}

async function createDocumentWithPages(imageFileUris: string[]) {
  /**
   * Create a document with a UUID
   * Add images from `imageFileUris` as document pages
   */
  const document = await ScanbotDocument.createDocumentFromImages({
    images: imageFileUris,
  });
}

async function loadDocument(documentID: string) {
  /** Load a document from storage by ID */
  const document = await ScanbotDocument.loadDocument(documentID);
}

async function storedDocumentUUIDs() {
  /** Retrieve all the document IDs from the storage */
  const documentIDs = await ScanbotDocument.getStoredDocumentUuids();
}

async function reorderDocumentPages(documentID: string) {
  /** Load a document from storage by ID */
  const document = await ScanbotDocument.loadDocument(documentID);
  /** Swap the first and last page of the document */
  const documentWithReorderedPages = await ScanbotDocument.movePage({
    documentUuid: document.uuid,
    fromIndex: 0,
    toIndex: document.pages.length - 1,
  });
}

async function removeAllPagesFromDocument(documentID: string) {
  /** Remove all the pages from a document */
  const documentWithRemovedPages = await ScanbotDocument.removeAllPages(
    documentID,
  );
}

async function deleteDocument(documentID: string) {
  /** Delete a document from storage along with the document's PDF and TIFF files */
  await ScanbotDocument.deleteDocument(documentID);
}

async function deleteAllDocuments() {
  /** Delete all documents from storage along with the document's PDF and TIFF files */
  await ScanbotDocument.deleteAllDocuments();
}

async function cleanup() {
  /** Removes all the files generated by ScanbotSDK including the documents */
  await ScanbotSDK.cleanupStorage();
}
